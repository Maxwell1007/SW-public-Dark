using Content.Client.Message;
using Content.Shared.Imperial.Medieval.SkeletonInvasion;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Utility;
using Robust.Shared.Prototypes;

namespace Content.Client.Imperial.Medieval.SkeletonInvasion.Progression;

[GenerateTypedNameReferences]
public sealed partial class SkeletonUpgradeEntry : Control
{
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    public event Action<ProtoId<SkeletonUpgradePrototype>>? BuyPressed;
    public readonly SkeletonUpgradePrototype Prototype;

    public SkeletonUpgradeEntry(SkeletonUpgradePrototype prototype)
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Prototype = prototype;
        UpgradeName.SetMessage(Loc.GetString(prototype.Name));
        UpgradeDescription.SetMessage(Loc.GetString(prototype.Description));
        UpgradeIcon.Texture = prototype.Icon.Frame0();
        Cost.Text = Loc.GetString("morbius-progression-cost", ("points", prototype.Cost));

        var requiredNames = new List<string>();
        foreach (var required in prototype.Required)
        {
            if (_prototypes.TryIndex(required, out var prerequisite))
                requiredNames.Add(Loc.GetString(prerequisite.Name));
        }

        Requirements.SetMessage(requiredNames.Count == 0
            ? Loc.GetString("morbius-progression-no-requirements")
            : Loc.GetString("morbius-progression-requirements", ("upgrades", string.Join(", ", requiredNames))));

        BuyButton.Color = Color.Black;
        BuyButton.BorderColor = Color.WhiteSmoke;
        BuyButton.HoveredColor = Color.FromHex("#424242FF");
        BuyButton.OnPressed += _ => BuyPressed?.Invoke(prototype.ID);
    }

    public void UpdateAllowance(SkeletonProgressionBuiState state)
    {
        var shared = Prototype.SharedEffect != SkeletonSharedUpgradeEffect.None;
        var purchasedUpgrades = shared ? state.PurchasedSharedUpgrades : state.PurchasedUpgrades;
        var points = shared ? state.SharedPoints : state.Points;
        var purchased = purchasedUpgrades.Contains(Prototype.ID);
        var requirementsMet = true;
        foreach (var required in Prototype.Required)
            requirementsMet &= purchasedUpgrades.Contains(required);

        var canBuy = state.CanBuy && !purchased && requirementsMet && points >= Prototype.Cost;
        BuyButton.Button.Disabled = !canBuy;
        BuyText.Text = Loc.GetString(purchased ? "morbius-progression-purchased" : "morbius-progression-buy");
        BuyButton.UpdateColor();

        Panel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.Black,
            BorderColor = purchased ? Color.LimeGreen : canBuy ? Color.Gold : Color.Crimson,
            BorderThickness = new(2),
        };
    }
}
