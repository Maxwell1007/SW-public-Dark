using System.Numerics;
using Content.Shared.Imperial.Medieval.SkeletonInvasion;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;

namespace Content.Client.Imperial.Medieval.SkeletonInvasion.Progression;

[GenerateTypedNameReferences]
public sealed partial class SkeletonProgressionWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    public event Action<ProtoId<SkeletonUpgradePrototype>>? BuyPressed;

    private readonly Dictionary<ProtoId<SkeletonUpgradePrototype>, SkeletonUpgradeEntry> _entries = new();
    private bool _dragging;

    public SkeletonProgressionWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Recenter.OnPressed += _ => Upgrades.SetOffset(Vector2.Zero);
        TreePanel.OnKeyBindDown += OnTreeKeyDown;
        TreePanel.OnKeyBindUp += OnTreeKeyUp;
    }

    public void Populate(SkeletonProgressionBuiState state)
    {
        PointsCounter.Text = Loc.GetString("morbius-progression-points", ("points", state.Points));

        foreach (var id in new List<ProtoId<SkeletonUpgradePrototype>>(_entries.Keys))
        {
            if (state.AvailableUpgrades.Contains(id))
                continue;

            var entry = _entries[id];
            Upgrades.RemoveChild(entry);
            entry.Dispose();
            _entries.Remove(id);
        }

        foreach (var id in state.AvailableUpgrades)
        {
            if (!_entries.TryGetValue(id, out var entry))
            {
                if (!_prototypes.TryIndex(id, out var prototype))
                    continue;

                entry = new SkeletonUpgradeEntry(prototype);
                entry.BuyPressed += upgrade => BuyPressed?.Invoke(upgrade);
                _entries.Add(id, entry);
                Upgrades.AddChild(entry);
            }

            entry.UpdateAllowance(state);
        }
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (_dragging)
            Upgrades.SetOffset(Upgrades.Offset + args.Relative);
    }

    private void OnTreeKeyDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _dragging = true;
    }

    private void OnTreeKeyUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _dragging = false;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return _dragging ? DragMode.None : base.GetDragModeFor(relativeMousePos);
    }
}
