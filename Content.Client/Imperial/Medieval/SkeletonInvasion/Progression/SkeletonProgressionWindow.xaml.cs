using System.Numerics;
using Content.Shared.Imperial.Medieval.SkeletonInvasion;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;

namespace Content.Client.Imperial.Medieval.SkeletonInvasion.Progression;

[GenerateTypedNameReferences]
public sealed partial class SkeletonProgressionWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    public event Action<ProtoId<SkeletonUpgradePrototype>>? BuyPressed;

    private readonly Dictionary<ProtoId<SkeletonUpgradePrototype>, SkeletonUpgradeEntry> _entries = new();
    private readonly Dictionary<ProtoId<SkeletonUpgradePrototype>, SkeletonUpgradeEntry> _sharedEntries = new();
    private SkeletonUpgradeLayout? _draggedLayout;

    public SkeletonProgressionWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        TabContainer.SetTabTitle(PersonalTab, Loc.GetString("morbius-progression-personal-tab"));
        TabContainer.SetTabTitle(SharedTab, Loc.GetString("morbius-progression-shared-tab"));
        Recenter.OnPressed += _ => Upgrades.SetOffset(Vector2.Zero);
        SharedRecenter.OnPressed += _ => SharedUpgrades.SetOffset(Vector2.Zero);
        TreePanel.OnKeyBindDown += args => OnTreeKeyDown(args, Upgrades);
        TreePanel.OnKeyBindUp += OnTreeKeyUp;
        SharedTreePanel.OnKeyBindDown += args => OnTreeKeyDown(args, SharedUpgrades);
        SharedTreePanel.OnKeyBindUp += OnTreeKeyUp;
    }

    public void Populate(SkeletonProgressionBuiState state)
    {
        PointsCounter.Text = Loc.GetString("morbius-progression-points", ("points", state.Points));
        SharedPointsCounter.Text = Loc.GetString("morbius-progression-shared-points", ("points", state.SharedPoints));
        PopulateUpgrades(state.AvailableUpgrades, _entries, Upgrades, state);
        PopulateUpgrades(state.AvailableSharedUpgrades, _sharedEntries, SharedUpgrades, state);
    }

    private void PopulateUpgrades(List<ProtoId<SkeletonUpgradePrototype>> available,
        Dictionary<ProtoId<SkeletonUpgradePrototype>, SkeletonUpgradeEntry> entries,
        SkeletonUpgradeLayout layout, SkeletonProgressionBuiState state)
    {
        foreach (var id in new List<ProtoId<SkeletonUpgradePrototype>>(entries.Keys))
        {
            if (available.Contains(id))
                continue;

            var entry = entries[id];
            layout.RemoveChild(entry);
            entry.Dispose();
            entries.Remove(id);
        }

        foreach (var id in available)
        {
            if (!entries.TryGetValue(id, out var entry))
            {
                if (!_prototypes.TryIndex(id, out var prototype))
                    continue;

                entry = new SkeletonUpgradeEntry(prototype);
                entry.BuyPressed += upgrade => BuyPressed?.Invoke(upgrade);
                entries.Add(id, entry);
                layout.AddChild(entry);
            }

            entry.UpdateAllowance(state);
        }
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (_draggedLayout is { } layout)
            layout.SetOffset(layout.Offset + args.Relative);
    }

    private void OnTreeKeyDown(GUIBoundKeyEventArgs args, SkeletonUpgradeLayout layout)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggedLayout = layout;
    }

    private void OnTreeKeyUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggedLayout = null;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return _draggedLayout != null ? DragMode.None : base.GetDragModeFor(relativeMousePos);
    }
}
